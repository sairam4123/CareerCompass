import { MdAutorenew, MdShare } from "react-icons/md";
import Spinner from "../components/Spinner";
import { useNavigate, useParams } from "react-router";
import Button from "../components/Button";
import { Bounce, toast, ToastContainer } from "react-toastify";
import FeedbackForm from "../forms/FeedbackForm";
import { useState } from "react";
import Answers from "./Answers";
import ResultsStream from "../components/ResultStream";

export default function Result({ userId: defaultUserId, shared = false }: { userId?: string | null; shared?: boolean }) {
  const { userId: paramUserId } = useParams();
  const navigate = useNavigate();
  const userId = defaultUserId ?? paramUserId;

  const [isFeedbackFormVisible, setIsFeedbackFormVisible] = useState(false);
  // useEffect(() => {
  //   if (shared) return;
  //   const timer = setTimeout(() => {
  //     setIsFeedbackFormVisible(true);
  //   }, 5000);
  //   return () => clearTimeout(timer);
  // }, []);


  return (
    <main className="p-4 flex flex-auto justify-center items-center min-h-screen pb-10 bg-gradient-to-br from-30% from-extra-light/25 via-extra-light to-light">
      <section
        className={`flex h-full flex-col justify-center items-center ${!userId ? "" : "mt-12"}`}
      >
        {userId && <h1 className="text-center font-bold text-6xl">Best Options</h1>}
        {/* {error && <p className="text-red-500 p-2">{error.message}</p>} */}
        {(!userId) && (
          <div className="flex flex-col animate-pulse items-center flex-1 mt-4 gap-2">
            <Spinner color="normal" size="large" />
            <p className="w-full md:w-1/2 lg:w-2/3 text-center">
              Our mascots are at work figuring your career for you!
            </p>
          </div>
        )}
        { userId && <ResultsStream userId={userId} />}
        { userId && !shared && <div className="flex flex-col gap-4 mt-8">
          <h1 className="text-center font-bold text-4xl">Your Answers</h1>
          <Answers userId={userId} />
        </div>}
        { userId && (<p className="text-center text-extra-dark mt-12">
            Note: These results are generated by AI and are not <span className="font-bold">100%</span> accurate.<br></br>They are based on the questions you answered and just a suggestion.<br></br>
            Please consult with a <span className="font-bold">career counselor</span> for more accurate results.
        </p>)}
        {/* { && userId && (<ResultsTable results={.results} />)} */}
        { userId && !shared && (<div className={`flex-1 flex flex-row w-full transition-all items-center justify-center gap-8 mt-4`}>
          <Button icon={<MdAutorenew />} text="Start Over" onClick={() => navigate("/")} />
            <Button icon={<MdShare />} text="Share" onClick={() => {
              navigator.clipboard.writeText(`${window.location.origin}/share/${userId}`); 
              // alert user the link has been copied
            toast.success("Link copied to clipboard!", { position: "top-right" });
            setIsFeedbackFormVisible(true);
          }} />
          </div>)}
        { userId && shared && (<div className="flex flex-col transition-all items-center justify-center mt-16">
          <p className="text-center text-extra-dark mt-2">This is a shared result. You can try the quiz yourself to get your own results.</p>
          <div className="flex-1 flex flex-row w-full transition-all items-center justify-center">
          <Button icon={<MdAutorenew />} text="Let's try" onClick={() => navigate("/")} />
          </div></div>)}

      </section>
      <ToastContainer
        position="top-right"
        autoClose={5000}
        hideProgressBar={false}
        newestOnTop={false}
        closeOnClick={false}
        rtl={false}
        pauseOnFocusLoss
        draggable
        pauseOnHover
        theme="light"
        transition={Bounce}
      />
      <FeedbackForm userId={userId ?? ""} isVisible={isFeedbackFormVisible} setIsVisible={(v) => {setIsFeedbackFormVisible(v)}} />
    </main>
  );
}
